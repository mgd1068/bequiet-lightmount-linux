#!/usr/bin/env python3
"""Verifies the CRC16/MODBUS checksum hypothesis against all 20 known Interface-2
report frames from the public usbmon3 capture (OpenRGB issue #4950).

One-off reverse-engineering/verification script, not part of the project's C++
codebase (see DECISIONS.md for the project's C-like C++ coding style — this
script documents how a fact in PROTOCOL.md was derived, it does not talk to
the device). Frame data below is copied verbatim from
docs/evidence/usbmon3_decoded_commands.txt.

Run: python3 checksum_verification.py
Expected: "20/20 frames match CRC16/MODBUS over bytes[0:62], little-endian".
"""

