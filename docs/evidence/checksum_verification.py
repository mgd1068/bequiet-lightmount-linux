def crc16_modbus(data: bytes) -> int:
    """CRC16/MODBUS: poly=0x8005, init=0xFFFF, refin=True, refout=True, xorout=0x0000."""
    crc = 0xFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            if crc & 0x0001:
                crc = (crc >> 1) ^ 0xA001  # reflected poly 0x8005
            else:
                crc >>= 1
    return crc


def main() -> None:
    ok = 0
    for frame_no, hexstr in FRAMES:
        report = bytes.fromhex(hexstr)
        assert len(report) == 64, f"frame {frame_no}: expected 64 bytes, got {len(report)}"
        computed = crc16_modbus(report[0:62])
        stored_le = report[62] | (report[63] << 8)
        match = computed == stored_le
        ok += match
        print(f"frame {frame_no}: computed={computed:04x} stored={stored_le:04x} {'OK' if match else 'MISMATCH'}")
    print(f"\n{ok}/{len(FRAMES)} frames match CRC16/MODBUS over bytes[0:62], little-endian")
    assert ok == len(FRAMES), "checksum hypothesis falsified"


if __name__ == "__main__":
    main()
